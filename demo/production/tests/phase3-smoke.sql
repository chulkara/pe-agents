-- Run as postgres after migrations 003 to 011 and the data-room revocation migration.
-- Uses fictional, confirmed identities only inside a subtransaction. No Auth emails or model calls.
-- All fixtures, invitations, signatures, tickets, jobs and the test house setting are rolled back.
-- Refuses to run once a real house firm is configured.
do $audit$
<<phase3>>
declare
 advisor uuid=gen_random_uuid(); seller uuid=gen_random_uuid(); buyer uuid=gen_random_uuid(); outsider uuid=gen_random_uuid();
 suffix text=replace(gen_random_uuid()::text,'-',''); advisor_mail text; seller_mail text; buyer_mail text;
 firm uuid; portal uuid; request uuid; letter uuid; file_id uuid; listing uuid; buyer_id uuid; access_id uuid; item uuid; review_id uuid; job_id uuid;
 invite text; code text; path text; f jsonb; paired jsonb; claimed jsonb; opened jsonb; n integer; body text;
begin
 if exists(select 1 from kalling_private.brokerage_settings) then raise exception 'Run this isolated smoke test before configuring the production house firm.'; end if;
 advisor_mail='advisor-'||suffix||'@kalling.invalid'; seller_mail='seller-'||suffix||'@kalling.invalid'; buyer_mail='buyer-'||suffix||'@kalling.invalid';
 begin
  insert into auth.users(id,email,email_confirmed_at) values(advisor,advisor_mail,now()),(seller,seller_mail,now()),(buyer,buyer_mail,now()),(outsider,'outsider-'||suffix||'@kalling.invalid',now());
  execute 'set local role authenticated';
  perform set_config('request.jwt.claim.sub',advisor::text,true);
  firm=public.kalling_create_firm('Fictional Kalling validation',jsonb_build_object('firm',jsonb_build_object('name','Fictional Kalling validation'),'companies',jsonb_build_array(jsonb_build_object('id','phase3-smoke','name','Fictional HVAC company')),'deals','[]'::jsonb,'events','[]'::jsonb));
  perform public.kalling_brokerage_set_house(firm);
  portal=public.kalling_portal_create(firm,'phase3-smoke','Fictional HVAC company','Fictional Seller',seller_mail,jsonb_build_object('name','Fictional Advisor','email',advisor_mail),'Fictional validation only.');
  perform public.kalling_portal_set_gate(portal,true);
  request=public.kalling_portal_save_request(portal,jsonb_build_object('title','Profit and loss statement, 2025','needed','A fictional annual statement for testing.','why','Validate the earnings review workflow.','sharing','Only advisors until owner approval.','contact',jsonb_build_object('name','Fictional Advisor','email',advisor_mail)));
  invite=public.kalling_portal_invite(portal);
  body=repeat('FICTIONAL VALIDATION ONLY. No real engagement or fee agreement. ',6);
  letter=public.kalling_letter_save(portal,jsonb_build_object('templateVersion','smoke-test-v1','input',jsonb_build_object('ownerName','Fictional Seller','advisorName','Fictional Advisor'),'text',body));
  perform public.kalling_letter_ready(letter);
  perform set_config('request.jwt.claim.sub',seller::text,true);
  perform public.kalling_portal_accept(invite);
  select count(*) into n from public.kalling_portal_requests where id=request;
  if n<>0 then raise exception 'Unsigned engagement exposed document requests.'; end if;
  perform public.kalling_letter_sign(letter,'Fictional Seller',true);
  perform set_config('request.jwt.claim.sub',advisor::text,true);
  perform public.kalling_letter_countersign(letter,'Fictional Advisor',true);
  perform set_config('request.jwt.claim.sub',seller::text,true);
  select count(*) into n from public.kalling_portal_requests where id=request;
  if n<>1 then raise exception 'Countersigning did not open requests.'; end if;
  select count(*) into n from public.kalling_workspaces where firm_id=firm;
  if n<>0 then raise exception 'Seller can read advisor workspace.'; end if;
  f=public.kalling_portal_reserve_file(request,'fictional-2025.pdf','application/pdf',10,repeat('a',64));
  file_id=(f#>>'{file,id}')::uuid; path=f#>>'{file,object_path}';
  insert into storage.objects(bucket_id,name,metadata) values('kalling-portal',path,'{"size":10,"mimetype":"application/pdf"}');
  perform public.kalling_portal_finish_file(file_id);
  perform public.kalling_portal_submit(request);
  perform set_config('request.jwt.claim.sub',advisor::text,true);
  perform public.kalling_portal_review(request,'Accepted','Fictional source reviewed.');
  perform public.kalling_portal_save_text(file_id,jsonb_build_object('status','ok','pages',jsonb_build_array(jsonb_build_object('page',1,'text','2025 Revenue $2,000,000. Net profit $100,000.')),'textHash',repeat('b',64),'extractor','fictional-test'));
  review_id=public.kalling_portal_publish_review(portal,'{"kind":"cim","version":1,"title":"Fictional memorandum","sections":[{"id":"overview","title":"Overview","text":"Fictional test only."}]}'::jsonb);
  perform set_config('request.jwt.claim.sub',seller::text,true);
  perform public.kalling_portal_decide_review(review_id,'Approved','[]'::jsonb);
  select count(*) into n from public.kalling_portal_file_text t where t.file_id=phase3.file_id;
  if n<>0 then raise exception 'Seller can read private extracted source text.'; end if;
  perform set_config('request.jwt.claim.sub',advisor::text,true);
  listing=public.kalling_listing_save(jsonb_build_object('companyId','phase3-smoke','headline','Fictional residential HVAC service company','region','Central Jersey','summary',repeat('Fictional sample for isolated database validation. ',4),'askingPrice',1500000,'revenue',2000000,'sde',300000,'highlights',jsonb_build_array('Service agreements','Residential work','Experienced technicians'),'confidential',jsonb_build_object('businessName','Confidential Test HVAC','city','Edison')));
  perform public.kalling_listing_set_status(listing,'Live');
  item=public.kalling_dataroom_save_item(jsonb_build_object('listingId',listing,'portalId',portal,'fileId',file_id,'displayName','Fictional annual statement','folder','Financials','tier','After NDA','allowDownload',false));
  perform public.kalling_dataroom_set_status(listing,'Proposed');
  perform set_config('request.jwt.claim.sub',seller::text,true);
  perform public.kalling_dataroom_owner_decide(array[item],'Approved','');
  perform set_config('request.jwt.claim.sub',advisor::text,true);
  perform public.kalling_dataroom_set_status(listing,'Published');
  perform set_config('request.jwt.claim.sub',buyer::text,true);
  buyer_id=public.kalling_buyer_save_profile('{"name":"Fictional Buyer","type":"Owner-operator","funds":"$500K to $1M","experience":"Fictional buyer with mechanical services experience for testing.","regions":["Central Jersey"],"maxPrice":2000000}'::jsonb);
  perform public.kalling_buyer_request_access(listing,'Fictional Buyer',true,'Fictional validation only.',repeat('c',64));
  select a.id into access_id from public.kalling_access a where a.buyer_id=phase3.buyer_id and a.listing_id=listing;
  perform set_config('storage.operation','object.get_authenticated',true);
  select count(*) into n from storage.objects where bucket_id='kalling-portal' and name=path;
  if n<>0 then raise exception 'Buyer read file before approval and logged open.'; end if;
  perform set_config('request.jwt.claim.sub',advisor::text,true);
  perform public.kalling_access_decide(access_id,'Approved','Fictional buyer reviewed.');
  perform set_config('request.jwt.claim.sub',buyer::text,true);
  opened=public.kalling_dataroom_open(item);
  if opened->>'ticket' is null then raise exception 'Approved buyer could not obtain logged ticket.'; end if;
  select count(*) into n from storage.objects where bucket_id='kalling-portal' and name=path;
  if n<>1 then raise exception 'Approved, logged buyer cannot fetch document.'; end if;
  perform set_config('storage.operation','object.sign',true);
  select count(*) into n from storage.objects where bucket_id='kalling-portal' and name=path;
  if n<>0 then raise exception 'Buyer can mint a signed URL.'; end if;
  perform set_config('storage.operation','object.get_authenticated',true);
  perform set_config('request.jwt.claim.sub',advisor::text,true);
  perform public.kalling_buyer_vet(buyer_id,'Restricted','Fictional revocation test.');
  perform set_config('request.jwt.claim.sub',buyer::text,true);
  select count(*) into n from storage.objects where bucket_id='kalling-portal' and name=path;
  if n<>0 then raise exception 'An old ticket retained access after buyer restriction.'; end if;
  if public.kalling_dataroom_open(item)->>'error' is null then raise exception 'Restricted buyer was not refused.'; end if;
  perform set_config('request.jwt.claim.sub',advisor::text,true);
  perform public.kalling_buyer_vet(buyer_id,'Registered','Restore fictional access for owner-revocation test.');
  perform set_config('request.jwt.claim.sub',seller::text,true);
  perform public.kalling_dataroom_owner_decide(array[item],'Removed','Fictional owner revocation test.');
  perform set_config('request.jwt.claim.sub',buyer::text,true);
  select count(*) into n from storage.objects where bucket_id='kalling-portal' and name=path;
  if n<>0 then raise exception 'An old ticket retained access after owner withdrawal.'; end if;
  perform set_config('request.jwt.claim.sub',outsider::text,true);
  select count(*) into n from public.kalling_portals where id=portal;
  if n<>0 then raise exception 'Unrelated account can read seller portal.'; end if;
  select count(*) into n from public.kalling_workspaces where firm_id=firm;
  if n<>0 then raise exception 'Unrelated account can read firm workspace.'; end if;
  select count(*) into n from public.kalling_listing_private where listing_id=listing;
  if n<>0 then raise exception 'Unrelated account can read confidential listing.'; end if;
  perform set_config('request.jwt.claim.sub',advisor::text,true);
  job_id=public.kalling_agent_enqueue(firm,'recast',jsonb_build_object('id','fictional-'||suffix,'playbook','local-recast-v1','company',jsonb_build_object('id','phase3-smoke'))::text);
  code=public.kalling_agent_create_pairing(firm,'Fictional worker validation');
  execute 'set local role anon';
  perform set_config('request.jwt.claim.sub','',true);
  paired=public.kalling_worker_pair(code,'kalling-worker-1');
  if public.kalling_worker_claim(paired->>'token') is not null then raise exception 'Version 1 worker claimed a drafting assignment.'; end if;
  perform public.kalling_worker_heartbeat(paired->>'token','ready','Fictional test.','kalling-worker-2','local-only test stub');
  claimed=public.kalling_worker_claim(paired->>'token');
  if claimed->>'id' is distinct from job_id::text then raise exception 'Version 2 worker did not claim the assignment.'; end if;
  if public.kalling_worker_claim(paired->>'token')->>'lease_token' is distinct from claimed->>'lease_token' then raise exception 'Interrupted worker did not resume the same lease.'; end if;
  if public.kalling_worker_finish(paired->>'token',job_id,(claimed->>'lease_token')::uuid,jsonb_build_object('id','fictional-'||suffix,'executionPolicy','local-only-required-v2','testFixture',true)::text) is distinct from 'ok' then raise exception 'Worker result was not recorded.'; end if;
  execute 'reset role';
  select count(*) into n from public.kalling_agent_jobs where id=job_id and status='succeeded';
  if n<>1 then raise exception 'Worker assignment failed to complete.'; end if;
  -- This sentinel rolls back the entire fixture subtransaction. Any other error aborts the audit.
  raise exception using errcode='PZ001',message='Fictional smoke test passed; roll back fixtures.';
 exception when sqlstate 'PZ001' then null;
 end;
end $audit$;
select jsonb_build_object('status','passed','fixtures_retained',false,'checks',jsonb_build_array('seller engagement gate','file reservation and RLS upload','document acceptance and private source text','owner memorandum approval','anonymous listing','NDA approval','logged authenticated download','signed URL denial','buyer and owner revocation','unrelated account isolation','worker version gate','interrupted lease recovery','local-only result contract')) as phase3_validation;
